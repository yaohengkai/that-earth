function normalise(value) {
  return String(value).replace(/\s+/g, " ").trim();
}

function hasCjk(value) {
  return /[\u3400-\u9fff]/.test(value);
}

export function detectSystemLanguage() {
  const code = (navigator.languages && navigator.languages[0]) || navigator.language || "en";
  return String(code).toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function getLanguage() {
  return current;
}

export function t(key) {
  const entry = MESSAGES[key];
  if (!entry) return key;
  return entry[current] || entry.en;
}

const textRecords = [];
const attrRecords = [];
let ready = false;

function collect() {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    if (node.nodeValue && hasCjk(node.nodeValue)) {
      textRecords.push({ node, raw: node.nodeValue });
    }
    node = walker.nextNode();
  }

  document.querySelectorAll("*").forEach((element) => {
    const attrs = {};
    ["aria-label", "title", "alt", "placeholder"].forEach((name) => {
      if (element.hasAttribute(name)) {
        const value = element.getAttribute(name);
        if (hasCjk(value)) attrs[name] = value;
      }
    });
    if (Object.keys(attrs).length) attrRecords.push({ element, attrs });
  });
}

function applyText(lang) {
  for (const record of textRecords) {
    if (lang === "zh") {
      record.node.nodeValue = record.raw;
      continue;
    }
    const key = normalise(record.raw);
    const translated = EN_TEXT[key];
    if (!translated) {
      record.node.nodeValue = record.raw;
      continue;
    }
    const leading = record.raw.match(/^\s*/)[0];
    const trailing = record.raw.match(/\s*$/)[0];
    record.node.nodeValue = leading + translated + trailing;
  }

  for (const record of attrRecords) {
    for (const [name, original] of Object.entries(record.attrs)) {
      if (lang === "zh") {
        record.element.setAttribute(name, original);
        continue;
      }
      const translated = EN_ATTRS[normalise(original)];
      record.element.setAttribute(name, translated || original);
    }
  }
}

function setMetaContent(selector, value) {
  const element = document.querySelector(selector);
  if (element) element.setAttribute("content", value);
}

function applyMeta(lang) {
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  const strings = META[lang];
  document.title = strings.title;
  setMetaContent('meta[name="description"]', strings.description);
  setMetaContent('meta[property="og:title"]', strings.ogTitle);
  setMetaContent('meta[property="og:description"]', strings.ogDescription);
  setMetaContent('meta[name="twitter:title"]', strings.twitterTitle);
  setMetaContent('meta[name="twitter:description"]', strings.twitterDescription);
  setMetaContent('meta[property="og:locale"]', strings.locale);
  setMetaContent('meta[property="og:image:alt"]', strings.title);

  const ld = document.querySelector('script[type="application/ld+json"]');
  if (ld) {
    try {
      const data = JSON.parse(ld.textContent);
      data.alternateName = strings.alternateName;
      data.description = strings.ldDescription;
      data.inLanguage = lang === "zh" ? "zh-CN" : "en";
      ld.textContent = JSON.stringify(data, null, 2);
    } catch (error) {}
  }
}

export function applyLanguage(lang, source = "system") {
  current = lang === "zh" ? "zh" : "en";
  document.documentElement.dataset.lang = current;
  document.documentElement.dataset.langSource = source;
  applyText(current);
  applyMeta(current);
  window.dispatchEvent(new CustomEvent("that-earth:language", { detail: { lang: current } }));
}

export function initI18n() {
  if (!ready) {
    collect();
    ready = true;
  }
  const initial = document.documentElement.dataset.lang === "zh" || document.documentElement.dataset.lang === "en"
    ? document.documentElement.dataset.lang
    : detectSystemLanguage();
  applyLanguage(initial, document.documentElement.dataset.langSource || "system");
  return { getLanguage, t, applyLanguage };
}
